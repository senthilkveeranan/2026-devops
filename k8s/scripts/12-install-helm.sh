#!/bin/bash
################################################################################
# Script Name : 13-helm.sh
# Description : Install Helm Package Manager
# Kubernetes  : v1.29.15
# Helm        : v3.x
# Rocky Linux : 9.8
################################################################################

set -euo pipefail

################################################################################
# Variables
################################################################################

HELM_VERSION="v3.18.3"

################################################################################
# Colors
################################################################################

GREEN="\033[1;32m"
RED="\033[1;31m"
BLUE="\033[1;34m"
YELLOW="\033[1;33m"
NC="\033[0m"

export KUBECONFIG=/etc/kubernetes/admin.conf

################################################################################
# Root Check
################################################################################

if [[ $EUID -ne 0 ]]; then
    echo "Run as root."
    exit 1
fi

################################################################################
# Banner
################################################################################

echo
echo -e "${GREEN}"
echo "========================================================="
echo "        Installing Helm Package Manager"
echo "========================================================="
echo -e "${NC}"

################################################################################
# Verify Kubernetes Cluster
################################################################################

kubectl get nodes

################################################################################
# Download Helm
################################################################################

cd /tmp

curl -LO https://get.helm.sh/helm-${HELM_VERSION}-linux-amd64.tar.gz

################################################################################
# Verify Download
################################################################################

if [[ ! -f helm-${HELM_VERSION}-linux-amd64.tar.gz ]]; then
    echo "Helm download failed."
    exit 1
fi

################################################################################
# Extract Helm
################################################################################

tar -xzf helm-${HELM_VERSION}-linux-amd64.tar.gz

################################################################################
# Install Binary
################################################################################

install -m 755 linux-amd64/helm /usr/local/bin/helm

################################################################################
# Verify Installation
################################################################################

helm version

################################################################################
# Enable Bash Completion
################################################################################

helm completion bash >/etc/bash_completion.d/helm

################################################################################
# Add Required Repositories
################################################################################

echo

echo "Adding Helm Repositories..."

helm repo add bitnami https://charts.bitnami.com/bitnami

helm repo add ingress-nginx \
https://kubernetes.github.io/ingress-nginx

helm repo add prometheus-community \
https://prometheus-community.github.io/helm-charts

helm repo add grafana \
https://grafana.github.io/helm-charts

helm repo add longhorn \
https://charts.longhorn.io

################################################################################
# Update Repository
################################################################################

helm repo update
################################################################################
# Verify Helm Version
################################################################################

echo
echo "=================================================="
echo "Helm Version"
echo "=================================================="

helm version

################################################################################
# Verify Helm Environment
################################################################################

echo
echo "=================================================="
echo "Helm Environment"
echo "=================================================="

helm env

################################################################################
# Verify Repository List
################################################################################

echo
echo "=================================================="
echo "Helm Repository"
echo "=================================================="

helm repo list

################################################################################
# Search Charts
################################################################################

echo
echo "=================================================="
echo "Searching Charts"
echo "=================================================="

helm search repo nginx | head

echo

helm search repo prometheus | head

echo

helm search repo grafana | head

################################################################################
# Helm Cache
################################################################################

echo
echo "=================================================="
echo "Helm Cache"
echo "=================================================="

helm env | grep CACHE

################################################################################
# Helm Plugin Directory
################################################################################

echo
echo "=================================================="
echo "Helm Plugins"
echo "=================================================="

helm plugin list || true

################################################################################
# Test Namespace
################################################################################

kubectl create namespace helm-test --dry-run=client -o yaml | kubectl apply -f -

################################################################################
# Verify Namespace
################################################################################

kubectl get ns helm-test

################################################################################
# Save Report
################################################################################

cat >/root/helm-info.txt <<EOF

=========================================================
Helm Installation Report
=========================================================

Installation Date

$(date)

Helm Version

$(helm version)

Repositories

$(helm repo list)

Helm Environment

$(helm env)

=========================================================

EOF

################################################################################
# Success Banner
################################################################################

echo
echo "=========================================================="
echo " Helm Installation Completed Successfully"
echo "=========================================================="

echo

echo "Installed Repositories"

helm repo list

echo

echo "Helm Version"

helm version

echo

echo "Report"

echo "/root/helm-info.txt"

echo

echo "=========================================================="
